public class day4 {
    public static void main(String[] args) {
        // Tipe Data Numerik Bilangan Bulat
        int jumlahBuku = 10;
        byte anak_ke = 3;
        long jumlahUang = 500000000L;
        short tahunMasuk = 2025;
        System.out.println("Jumlah buku saya : " + jumlahBuku);
        System.out.println("Saya anak ke : " + anak_ke);
        System.out.println("jumlah uang saya : " + jumlahUang);
        System.out.println("Saya masuk kuliah pada tahun : " + tahunMasuk);
        //int digunakan untuk menyimpan bilangan bulat
       //byte digunakan untuk bilangan bulat yang nilainya relatif kecil
       //long digunakan untuk menyimpan bilangan bulat yang besar
      //short digunakan untuk menyimpan bilangan bulat dengan ukuran lebih kecil daripada int
    }
}
