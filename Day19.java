public class day19{
    public static void main(String[] args) {

        //Konversi manual/paksa (Dari tipe data besar ke kecil)

            //long ke int 
            long nilaiE = 200;
            int nilaiF = (int) nilaiE;
            System.out.println("long ke int : " + nilaiE);

            //double ke int
            double nilaiA = 85.5;
            int nilaiB = (int) nilaiA;
            System.out.println("double ke int : " + nilaiB);

            //float ke int 
            float nilaiC = 72.8f;
            int nilaiD = (int) nilaiC;
            System.out.println("float ke int : " + nilaiC);         
}
}
